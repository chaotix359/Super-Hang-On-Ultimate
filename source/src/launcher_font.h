static const uint8_t *lf_glyph(char c) {
    if (c >= 'a' && c <= 'z') c = (char)(c - 32);
    for (unsigned i = 0; i < sizeof lf_glyphs / sizeof lf_glyphs[0]; i++) if (lf_glyphs[i].c == c) return lf_glyphs[i].r;
    return lf_glyphs[44].r;   /* '?' for anything else */
}
